const PLANS = {};
function numrow(text) {
 return text.trim().split(/\s+/).map(s=>s==='-' ? null : Number(s));
}
function rows(text){
 return text.trim().split('\n').filter(Boolean).map((line)=>{
  const [area, name, vals] = line.split('|').map(s=>s.trim());
  return { area, name, values:numrow(vals) };
 });
}
function define(id, cfg){
 const grades = cfg.grades.split('|');
 const arrayKeys=['mandatory','part','max','extracurricular','correction','other','grand'];
 for(const k of arrayKeys) cfg[k] = numrow(cfg[k]);
 cfg.rows = rows(cfg.rows);
 cfg.correctionRows = rows(cfg.correctionRows||'');
 cfg.grades = grades;
 cfg.id=id;
 for(const r of [...cfg.rows,...cfg.correctionRows]) {
  if(r.values.length!==grades.length) throw new Error(`${id}: ${r.name} has ${r.values.length} values, expected ${grades.length}`);
 }
 for(const k of arrayKeys) if(cfg[k].length!==grades.length) throw new Error(`${id}: ${k} length not ${grades.length}`);
 PLANS[id]=cfg;
}

